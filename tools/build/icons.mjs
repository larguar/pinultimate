// Generates snippets/icon.liquid from the Bootstrap Icons listed in src/icons.json,
// plus the theme's own icons in src/icons/*.svg.
// Usage in Liquid: {% render 'icon', name: 'cart', class: 'fs-4' %}
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const custom = readdirSync('src/icons').filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4));
const names = [...JSON.parse(readFileSync('src/icons.json')), ...custom];
const cases = names.map((name) => {
  const file = custom.includes(name) ? `src/icons/${name}.svg` : `node_modules/bootstrap-icons/icons/${name}.svg`;
  const svg = readFileSync(file, 'utf8')
    .trim()
    .replace(/ width="16" height="16"/, ' width="1em" height="1em"')
    .replace(/ class="[^"]*"/, ' class="bi bi-{{ name }} {{ class }}" aria-hidden="true" focusable="false"');
  return `  {%- when '${name}' -%}\n    ${svg.replace(/\n\s*/g, '')}`;
});

writeFileSync(
  'snippets/icon.liquid',
  `{%- comment -%}
  Generated by tools/build/icons.mjs from Bootstrap Icons (MIT) and src/icons/*.svg.
  Do not edit by hand: add a Bootstrap icon name to src/icons.json, or an SVG to
  src/icons/, and run \`npm run build:icons\`.

  Accepts:
  - name {String}: Bootstrap Icons name
  - class {String}: extra classes (optional)
{%- endcomment -%}
{%- case name -%}
${cases.join('\n')}
{%- endcase -%}
`
);
console.log(`snippets/icon.liquid: ${names.length} icons`);
